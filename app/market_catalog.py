def buyer_band(n: int) -> str:
    for lo, hi, label in BUYER_BANDS:
        if n >= lo and (hi is None or n <= hi):
            return label
    return ""


def qty_band(total: float | None) -> tuple[float | None, float | None]:
    """월 수요 합계 -> (구간 하한, 구간 상한). 수량을 모르면 (None, None)."""
    if total is None:
        return None, None
    prev = 0.0
    for step in QTY_LADDER:
        if total <= step:
            return prev, step
        prev = step
    return QTY_LADDER[-1], None



