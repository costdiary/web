def norm(s: str | None) -> str:
    """식자재/표준 품목 이름 정규화. services.norm_name과 동일한 규칙."""
    s = _PAREN.sub("", s or "")
    s = _SPEC.sub("", s)
    return _JUNK.sub("", s).lower()


